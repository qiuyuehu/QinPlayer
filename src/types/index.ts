// =============================================================================
// QinPlayer — 公共类型定义
// =============================================================================
// 主进程与渲染进程共享的核心数据类型
// 所有 IPC 通信和 Zustand Store 都基于这些类型
// =============================================================================

// ---------------------------------------------------------------------------
// 歌曲
// ---------------------------------------------------------------------------

export interface Track {
  id: number               // 数据库自增 ID
  filePath: string         // 文件绝对路径（用于 qinplayer:// 协议加载）
  fileName: string         // 文件名（标签缺失时兜底显示）
  title: string            // 歌名（来自 ID3 标签，缺失则用文件名）
  artist: string           // 歌手
  album: string            // 专辑名
  duration: number         // 时长（秒）
  coverPath: string | null // 封面图片路径（从 ID3 提取或同目录 cover.jpg）
  mtime: number            // 文件最后修改时间（增量扫描用）
  playCount: number        // 播放次数
  createdAt: string        // 入库时间
}

// ---------------------------------------------------------------------------
// 歌单
// ---------------------------------------------------------------------------

export interface Playlist {
  id: number               // 数据库自增 ID
  name: string             // 歌单名称
  createdAt: string        // 创建时间
  songCount?: number       // 歌曲数量（查询时填充）
}

// ---------------------------------------------------------------------------
// 专辑
// ---------------------------------------------------------------------------

export interface Album {
  name: string             // 专辑名
  artist: string           // 歌手
  coverPath: string | null // 封面路径
  songs: Track[]           // 专辑内歌曲
}

// ---------------------------------------------------------------------------
// 歌词
// ---------------------------------------------------------------------------

export interface LyricLine {
  time: number             // 时间戳（秒）
  text: string             // 歌词文本（原文）
  translation?: string     // 翻译文本（可选，双语歌词时存在）
}

// ---------------------------------------------------------------------------
// 枚举 / 联合类型
// ---------------------------------------------------------------------------

// 播放模式
export type PlayMode = 'sequential' | 'loop' | 'shuffle'

// 主题
export type Theme = 'dark' | 'light' | 'system'

// 排序方式
export type SortBy = 'added' | 'playCount'
export type SortOrder = 'asc' | 'desc'
